import { execFileSync } from "node:child_process";
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const examplesDir = path.join(root, "components/examples");
const outFile = path.join(root, "components/docs/example-registry.tsx");

const names = await readdir(examplesDir);
const files = names.filter((file) => file.endsWith(".tsx")).toSorted();

const entries = files
  .map((file) => {
    const name = file.replace(/\.tsx$/u, "");
    return `  "${name}": dynamic(() => import("@/components/examples/${name}")),`;
  })
  .join("\n");

const content = `"use client";

// Generated by scripts/build-examples.mjs. Do not edit by hand.
import dynamic from "next/dynamic";
import type { ComponentType } from "react";

export const examples: Record<string, ComponentType | undefined> = {
${entries}
};
`;

await writeFile(outFile, content);
// Format like the rest of the repo so regenerating leaves no diff.
execFileSync(path.join(root, "node_modules/.bin/oxfmt"), [outFile]);
console.log(`example registry: ${files.length} examples`);
