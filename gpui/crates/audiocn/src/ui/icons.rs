//! Icons: the [Phosphor](https://phosphoricons.com) set audiocn uses
//! (`@phosphor-icons/react`, regular and `weight="fill"`), painted as SVG data
//! so the crate needs no asset source.
//!
//! The path data is copied verbatim from `@phosphor-icons/react` 2.1.10
//! (MIT License, Copyright (c) 2020 Phosphor Icons). Names follow the React
//! components without the `Icon` suffix: `<CaretDownIcon />` →
//! [`IconName::CaretDown`]. Lucide equivalents are noted on each variant.
//!
//! ```ignore
//! Icon::new(IconName::Play).weight(IconWeight::Fill).size(px(16.0))
//! ```

use gpui::{
    App, Bounds, Element, ElementId, GlobalElementId, Hsla, InspectorElementId, IntoElement,
    LayoutId, Pixels, Radians, SharedString, Style, TransformationMatrix, Window, point, px, size,
};

use crate::motion::Instant;

macro_rules! svg {
    ($body:literal) => {
        concat!(
            "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 256 256\">",
            $body,
            "</svg>"
        )
    };
}

/// Phosphor icon weight. audiocn uses `regular` (default) and `fill`.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub enum IconWeight {
    #[default]
    Regular,
    Fill,
}

/// An icon element: `size-4` (16px) by default, coloured with the inherited
/// text colour (`currentColor`) unless [`Icon::color`] is set.
///
/// ```ignore
/// div().text_color(cx.theme().muted_foreground).child(Icon::new(IconName::Microphone))
/// ```
pub struct Icon {
    name: IconName,
    weight: IconWeight,
    size: Pixels,
    color: Option<Hsla>,
    spin: bool,
    rotation: f32,
}

impl Icon {
    pub fn new(name: IconName) -> Self {
        Self {
            name,
            weight: IconWeight::Regular,
            size: px(16.0),
            color: None,
            spin: false,
            rotation: 0.0,
        }
    }

    /// `weight="fill"` etc.
    pub fn weight(mut self, weight: IconWeight) -> Self {
        self.weight = weight;
        self
    }

    /// Shorthand for `.weight(IconWeight::Fill)`.
    pub fn fill(self) -> Self {
        self.weight(IconWeight::Fill)
    }

    /// Width and height (`size-4` = 16px, the default).
    pub fn size(mut self, size: Pixels) -> Self {
        self.size = size;
        self
    }

    /// Explicit colour; defaults to the inherited text colour.
    pub fn color(mut self, color: Hsla) -> Self {
        self.color = Some(color);
        self
    }

    /// `animate-spin`: one turn per second, linear.
    pub fn spin(mut self, spin: bool) -> Self {
        self.spin = spin;
        self
    }

    /// Static rotation in degrees (clockwise).
    pub fn rotate(mut self, degrees: f32) -> Self {
        self.rotation = degrees;
        self
    }

    pub fn icon_name(&self) -> IconName {
        self.name
    }
}

impl From<IconName> for Icon {
    fn from(name: IconName) -> Self {
        Icon::new(name)
    }
}

impl IntoElement for IconName {
    type Element = Icon;
    fn into_element(self) -> Icon {
        Icon::new(self)
    }
}

impl IntoElement for Icon {
    type Element = Self;
    fn into_element(self) -> Self {
        self
    }
}

fn spin_epoch() -> Instant {
    static EPOCH: std::sync::OnceLock<Instant> = std::sync::OnceLock::new();
    *EPOCH.get_or_init(Instant::now)
}

impl Element for Icon {
    type RequestLayoutState = ();
    type PrepaintState = ();

    fn id(&self) -> Option<ElementId> {
        None
    }

    fn source_location(&self) -> Option<&'static std::panic::Location<'static>> {
        None
    }

    fn request_layout(
        &mut self,
        _: Option<&GlobalElementId>,
        _: Option<&InspectorElementId>,
        window: &mut Window,
        cx: &mut App,
    ) -> (LayoutId, ()) {
        let style = Style {
            size: size(self.size.into(), self.size.into()),
            flex_shrink: 0.0,
            ..Style::default()
        };
        (window.request_layout(style, [], cx), ())
    }

    fn prepaint(
        &mut self,
        _: Option<&GlobalElementId>,
        _: Option<&InspectorElementId>,
        _: Bounds<Pixels>,
        _: &mut (),
        _: &mut Window,
        _: &mut App,
    ) {
    }

    fn paint(
        &mut self,
        _: Option<&GlobalElementId>,
        _: Option<&InspectorElementId>,
        bounds: Bounds<Pixels>,
        _: &mut (),
        _: &mut (),
        window: &mut Window,
        cx: &mut App,
    ) {
        let color = self.color.unwrap_or_else(|| window.text_style().color);
        let mut degrees = self.rotation;
        if self.spin {
            let t = Instant::now().duration_since(spin_epoch()).as_secs_f32();
            degrees += (t % 1.0) * 360.0;
            window.request_animation_frame();
        }
        let transform = if degrees == 0.0 {
            TransformationMatrix::unit()
        } else {
            let sf = window.scale_factor();
            let center = bounds.center();
            TransformationMatrix::unit()
                .translate(center.scale(sf))
                .rotate(Radians(degrees.to_radians()))
                .translate(point(-center.x, -center.y).scale(sf))
        };
        let (key, data) = self.name.svg(self.weight);
        let _ = window.paint_svg(
            bounds,
            SharedString::new_static(key),
            Some(data.as_bytes()),
            transform,
            color,
            cx,
        );
    }
}

